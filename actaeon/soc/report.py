"""Markdown case reports and the shift report."""

from __future__ import annotations

from collections import Counter

from ..hunt.attack_names import name as tname
from .graph import attack_chain, timeline
from .store import SocStore
from .util import ago

LABEL = {"true_positive": "True positive", "false_positive": "False positive", "benign": "Benign (expected)",
         "needs_analyst": "Needs an analyst", "logs_missing": "Logs missing", None: "Not triaged"}


def _md(s: str) -> str:
    return str(s or "").replace("\r", "").replace("|", "\\|")


def case_markdown(case: dict) -> str:
    r = case.get("report") or {}
    out = [f"# Case {case['id']}: {_md(case.get('title'))}", "",
           f"- AI verdict: **{LABEL.get(case.get('verdict'), case.get('verdict'))}** (confidence {case.get('confidence') or 0})",
           f"- Analyst verdict: {LABEL.get(case.get('analyst_verdict'), case.get('analyst_verdict')) if case.get('analyst_verdict') else 'not yet'}",
           f"- Severity: {case.get('severity_label')} ({case.get('severity')}), status {case.get('status')}",
           f"- Alerts: {len(case.get('alerts') or [])}, first {case.get('first_alert')}, last {case.get('last_alert')}", ""]
    if case.get("summary"):
        out += ["## Summary", "", _md(case["summary"]), ""]
    if r.get("findings"):
        out += ["## Findings", ""] + [f"- {_md(f.get('text'))} ({', '.join(f.get('evidence') or []) or 'no evidence'})"
                                      for f in r["findings"]] + [""]
    tl = timeline(case)
    if tl:
        out += ["## Timeline", "", "| Time | Kind | Event |", "|---|---|---|"]
        out += [f"| {t.get('time') or ''} | {t['kind']} | {_md(t.get('text'))[:300]} |" for t in tl] + [""]
    chain = attack_chain(case)
    if chain:
        out += ["## ATT&CK", ""] + [f"- {c['tactic']}: " + ", ".join(f"{t['id']} {t['name']}" for t in c["techniques"])
                                    for c in chain] + [""]
    if case.get("entities"):
        out += ["## Entities", ""] + [f"- {e['type']}: `{_md(e['value'])}`" for e in case["entities"][:80]] + [""]
    fix = r.get("fix") or {}
    if fix.get("steps") or fix.get("tuning"):
        out += [f"## Fix ({fix.get('type')})", ""] + [f"{i}. {_md(s)}" for i, s in enumerate(fix.get("steps") or [], 1)]
        if fix.get("tuning"):
            t = fix["tuning"]
            out.append(f"- Tuning: rule `{_md(t.get('rule'))}`"
                       + (f" on {t.get('entity_type')}=`{_md(t.get('entity_value'))}`" if t.get("entity_type") else "")
                       + f": {_md(t.get('reason'))}")
        out.append("")
    if case.get("actions"):
        out += ["## Response actions", "", "| Action | Target | Status | By |", "|---|---|---|---|"]
        out += [f"| {a['name']} | `{_md(a['target'])}` | {a['status']} | {a.get('decided_by') or ''} |"
                for a in case["actions"]] + [""]
    if r.get("gaps"):
        out += ["## Not checked", ""] + [f"- {_md(g)}" for g in r["gaps"]] + [""]
    if r.get("checks"):
        out += ["## Checks applied to the verdict", ""] + [f"- {_md(c)}" for c in r["checks"]] + [""]
    calls = [s for s in case.get("steps") or [] if s["kind"] == "call"]
    if calls:
        out += ["## Evidence", "", "| Id | Source | Arguments | Result |", "|---|---|---|---|"]
        import json
        out += [f"| E{s['n']} | {s['connector']}.{s['tool']} | `{_md(json.dumps(s['arguments'], default=str))[:200]}` | "
                f"{'ok' if s['ok'] else 'failed'} {_md(s.get('note'))[:80]} |" for s in calls] + [""]
    out.append("_Generated by Actaeon. The AI verdict is an assessment for an analyst to confirm._")
    return "\n".join(out)


def shift_markdown(store: SocStore, hours: int = 12) -> str:
    since = ago(hours=hours)
    cases = store.cases(since=since, limit=500)
    c = Counter(x.get("verdict") or "untriaged" for x in cases)
    out = [f"# Shift report: last {hours} hours", "",
           f"- Cases: {len(cases)} ({', '.join(f'{k} {v}' for k, v in c.most_common())})",
           f"- Open now: {sum(1 for x in cases if x['status'] != 'closed')}",
           f"- Actions waiting for approval: {sum(int(x.get('pending_actions') or 0) for x in cases)}", ""]
    tps = [x for x in cases if x.get("verdict") == "true_positive"]
    if tps:
        out += ["## True positives", ""]
        for x in tps:
            out.append(f"- **{_md(x['title'])}** ({x['severity_label']}, confidence {x.get('confidence')}, "
                       f"{x['status']}): {_md(x.get('summary'))[:400]}")
        out.append("")
    need = [x for x in cases if x["status"] == "needs_analyst"]
    if need:
        out += ["## Needs an analyst", ""] + [f"- {_md(x['title'])} ({x.get('verdict')}): "
                                             f"{_md(x.get('summary'))[:300]}" for x in need] + [""]
    techniques = Counter(t for x in cases for t in x.get("attack") or [])
    if techniques:
        out += ["## Techniques seen", ""] + [f"- {t} {tname(t)}: {n}" for t, n in techniques.most_common(10)] + [""]
    return "\n".join(out)
